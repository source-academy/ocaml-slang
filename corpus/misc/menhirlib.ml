(* MenhirLib is linked into the toplevel, for the parsers that Menhir generates (--table). A parser
   generated by Menhir 20260209 requires this version of the library, so an upgrade shows up here. *)
let () = MenhirLib.StaticVersion.require_20260209
let lexbuf = MenhirLib.LexerUtil.init "input.txt" (Lexing.from_string "a b")
let () = print_endline lexbuf.Lexing.lex_curr_p.Lexing.pos_fname
let () = Printf.printf "%d %d\n" lexbuf.Lexing.lex_curr_p.Lexing.pos_lnum lexbuf.Lexing.lex_curr_p.Lexing.pos_cnum
let _ = (MenhirLib.Convert.Simplified.traditional2revised : _ -> _)
;;
MenhirLib.LexerUtil.range (lexbuf.Lexing.lex_curr_p, lexbuf.Lexing.lex_curr_p);;
